"""Cryptographic primitives: passphrase KDF and AEAD wrapping.

All symmetric operations use AES-256-GCM. Passphrase derivation uses
PBKDF2-HMAC-SHA256 with a high iteration count (see KDF_ITERATIONS).
"""

from __future__ import annotations

import hashlib
import os

from cryptography.exceptions import InvalidTag
from cryptography.hazmat.primitives.ciphers.aead import AESGCM

from .errors import IntegrityError

#: PBKDF2-HMAC-SHA256 iteration count. Each iteration evaluates two
#: HMAC-SHA256 (four SHA-256 compression runs), so 600_000 iterations
#: cost well above 600k generic password-hash evaluations.
KDF_ITERATIONS = 600_000

#: Size in bytes of the per-library KDF salt.
SALT_SIZE = 16

#: Size in bytes of every key handled here (AES-256).
KEY_SIZE = 32

#: Size in bytes of AES-GCM nonces generated by this module.
NONCE_SIZE = 12


def random_bytes(length: int) -> bytes:
    """Return ``length`` cryptographically secure random bytes."""
    return os.urandom(length)


def derive_kek(passphrase: str, salt: bytes, iterations: int = KDF_ITERATIONS) -> bytes:
    """Derive a 256-bit key-encryption key from a passphrase and salt."""
    if len(salt) != SALT_SIZE:
        raise ValueError("salt must be SALT_SIZE bytes")
    return hashlib.pbkdf2_hmac(
        "sha256", passphrase.encode("utf-8"), salt, iterations, dklen=KEY_SIZE
    )


def aead_encrypt(key: bytes, plaintext: bytes, aad: bytes) -> bytes:
    """Encrypt with AES-256-GCM; output is nonce || ciphertext || tag."""
    nonce = random_bytes(NONCE_SIZE)
    return nonce + AESGCM(key).encrypt(nonce, plaintext, aad)


def aead_decrypt(key: bytes, blob: bytes, aad: bytes) -> bytes:
    """Decrypt data produced by :func:`aead_encrypt`.

    Raises :class:`keyescrow.errors.IntegrityError` on any authentication
    failure.
    """
    if len(blob) < NONCE_SIZE + 16:
        raise IntegrityError("blob too short")
    nonce, ct = blob[:NONCE_SIZE], blob[NONCE_SIZE:]
    try:
        return AESGCM(key).decrypt(nonce, ct, aad)
    except InvalidTag as exc:
        raise IntegrityError("authentication failed") from exc
